// Names that end in "а"/"я" but are male (exceptions to the rule)
const MALE_EXCEPTIONS = new Set([
  "илья","никита","данила","кузьма","фома","савва","лука","иона","коля","саша","митя","женя",
  "серёжа","андрюша","лёша","петя","ваня","алёша","миша","гриша","юра","федя","паша","стёпа",
  "гена","слава","дима","рома","тёма","сёма","яша","вася","витя","костя",
])

/**
 * Detect gender from a first name.
 * @returns "м" | "ж" | ""
 */
export function detectGender(firstName: string): "м" | "ж" | "" {
  if (!firstName) return ""

  const name = firstName.trim().toLowerCase()

  if (MALE_NAMES.has(name)) return "м"
  if (FEMALE_NAMES.has(name)) return "ж"

  // Fallback: morphological rules for Russian/Ukrainian
  // Male exceptions that end in а/я
  if (MALE_EXCEPTIONS.has(name)) return "м"

  // Endings strongly indicating female
  if (/(?:ья|ия|ея|уя|ова|ева|ина|ана|яна|ина|она|ачка|ечка|ушка|юшка|юня|юля|аша|яша|ала|яла|ила|ица|ника|лька|нька|ька)$/.test(name)) return "ж"
  if (/[аяь]$/.test(name) && !MALE_EXCEPTIONS.has(name)) return "ж"

  // Endings strongly indicating male
  if (/(?:ий|ей|ой|ый|ин|ын|он|ан|ен|ён|ём|им|ым|ов|ев|ёв|ав|ив|ув|юв)$/.test(name)) return "м"
  if (/[бвгджзйклмнпрстфхцчшщ]$/.test(name)) return "м"

  return ""
}
